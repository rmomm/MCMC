# Файл створюється C++ програмою: Run,Iteration,BestScore,Accuracy
df = pd.read_csv("mcmc_statistics.csv")

required = {"Run", "Iteration", "Accuracy"}
if not required.issubset(df.columns):
    raise ValueError("CSV повинен містити Run, Iteration та Accuracy")

# Графік 1: точність за кількістю ітерацій
plt.figure(figsize=(10, 6))
for run, group in df.groupby("Run"):
    group = group.sort_values("Iteration")
    plt.plot(group["Iteration"], group["Accuracy"], marker="o",
             label=f"Запуск {run}")

plt.axhline(95, linestyle="--", label="Поріг 95%")
plt.xlabel("Кількість ітерацій")
plt.ylabel("Точність дешифрування, %")
plt.title("Залежність точності дешифрування від кількості ітерацій MCMC")
plt.ylim(0, 105)
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.savefig("accuracy_by_iterations.png", dpi=200)
plt.show()

# Графік 2: кінцева точність кожного запуску
last = (df.sort_values("Iteration").groupby("Run").tail(1)
          .sort_values("Run"))
labels = ["1 — тотожний" if r == 1 else f"{r} — випадковий"
          for r in last["Run"]]

plt.figure(figsize=(10, 6))
bars = plt.bar(labels, last["Accuracy"])
plt.axhline(95, linestyle="--", label="Поріг 95%")
plt.xlabel("Запуск та тип початкового ключа")
plt.ylabel("Кінцева точність дешифрування, %")
plt.title("Залежність кінцевої точності від початкового ключа")
plt.ylim(0, 105)
plt.grid(axis="y")
plt.legend()
for bar, value in zip(bars, last["Accuracy"]):
    plt.text(bar.get_x() + bar.get_width()/2, value + 1,
             f"{value:.2f}%", ha="center")
plt.xticks(rotation=12)
plt.tight_layout()
plt.savefig("final_accuracy_by_initial_key.png", dpi=200)
plt.show()

