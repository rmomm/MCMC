import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm

d_values = [0.01, 1, 100]

BURN_IN = 10000

for d in d_values:
    filename = f"d_{str(d).replace('.', '_')}.csv"
    data = pd.read_csv(filename)

    iterations = data["Iteration"]
    theta = data["Theta"]

    plt.figure(figsize=(10, 5))
    plt.plot(iterations, theta)
    plt.title(f"Ланцюг Маркова (d = {d})")
    plt.xlabel("Номер ітерації")
    plt.ylabel("Значення theta")
    plt.grid()
    plt.tight_layout()
    plt.savefig(f"trace_d_{str(d).replace('.', '_')}.png")
    plt.show()


    samples = theta[BURN_IN:]

    plt.figure(figsize=(10, 5))

    plt.hist(
        samples,
        bins=50,
        density=True,
        alpha=0.7,
        label="Емпіричний розподіл"
    )

    x = np.linspace(min(samples), max(samples), 300)
    plt.plot(
        x,
        norm.pdf(x, loc=2.4, scale=np.sqrt(0.8)),
        label="Теоретичний розподіл N(2.4, 0.8)"
    )

    plt.title(f"Гістограма розподілу (d = {d})")
    plt.xlabel("Значення theta")
    plt.ylabel("Щільність")
    plt.legend()
    plt.grid()
    plt.tight_layout()
    plt.savefig(f"histogram_d_{str(d).replace('.', '_')}.png")
    plt.show()



